#!/usr/bin/env node
/**
 * Mirror bank migration emitter.
 *
 * The registry at src/data/mirrors/ is the source of truth for every mirror
 * question bank. This bundles it and writes a Supabase migration that upserts
 * the banks into `assessment_definitions`.
 *
 *   node scripts/emit-mirror-migrations.mjs
 *   node scripts/emit-mirror-migrations.mjs --check     # verify coverage only
 *   node scripts/emit-mirror-migrations.mjs --out path.sql
 *
 * Idempotent: the output filename is derived from a hash of the content, so
 * re-running with unchanged banks produces the same filename and no new
 * migration. Change the banks and the filename changes with them.
 */

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registryEntry = path.join(root, 'src/data/mirrors/registry.ts');
const migrationsDir = path.join(root, 'supabase/migrations');

const argv = process.argv.slice(2);
const checkOnly = argv.includes('--check');
const outIndex = argv.indexOf('--out');
const explicitOut = outIndex >= 0 ? argv[outIndex + 1] : null;

// ─── Load the registry ───

async function loadRegistry() {
  const outfile = path.join(root, 'node_modules/.cache/mirror-registry.mjs');
  await mkdir(path.dirname(outfile), { recursive: true });
  await build({
    entryPoints: [registryEntry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    outfile,
    logLevel: 'warning',
    // Mirrors the `@` alias in vite.config.ts / tsconfig.app.json.
    alias: { '@': path.join(root, 'src') },
  });
  const mod = await import(`${pathToFileURL(outfile).href}?t=${Date.now()}`);
  await rm(outfile, { force: true });
  return mod;
}

// ─── SQL helpers ───

/**
 * SQL string literal.
 *
 * Standard-conforming strings are on, so only single quotes need doubling.
 *
 * But a bank `intro` contains real newlines for paragraph breaks, and a raw
 * newline inside a literal makes each VALUES tuple span several physical
 * lines — which makes the generated migration unreviewable in a diff and
 * defeats line-based tooling. So anything containing a newline or a backslash
 * is emitted as an escape string (E'...'), where `\n` is a newline and `\` is
 * escaped as `\\`. Single quotes still double in an E-string.
 */
function q(value) {
  if (value === null || value === undefined) return 'NULL';
  const s = String(value);
  if (s.includes('\n') || s.includes('\r') || s.includes('\\')) {
    const escaped = s
      .replaceAll('\\', '\\\\')
      .replaceAll("'", "''")
      .replaceAll('\r\n', '\\n')
      .replaceAll('\n', '\\n')
      .replaceAll('\r', '\\r');
    return `E'${escaped}'`;
  }
  return `'${s.replaceAll("'", "''")}'`;
}

function jsonb(value) {
  if (value === null || value === undefined) return 'NULL';
  return `${q(JSON.stringify(value))}::jsonb`;
}

async function loadCheckpoints() {
  const src = await readFile(
    path.join(root, 'src/data/pre-journey/mirrors.ts'),
    'utf8',
  );
  const slugs = [...src.matchAll(/assessmentSlug: '([^']+)'/g)].map((m) => m[1]);
  return [...new Set(slugs)];
}

// ─── Emit ───

const COLUMNS = [
  'slug',
  'title',
  'subtitle',
  'tradition',
  'dimension_category',
  'intro',
  'cover_emoji',
  'estimated_minutes',
  'question_count',
  'questions',
  'scoring_logic',
  'result_types',
  'engine_hooks',
  'version',
  'is_active',
  'is_featured',
  'sort_order',
  'updated_at',
];

function rowFor(bank) {
  const r = bank.__row;
  const map = {
    slug: q(r.slug),
    title: q(r.title),
    subtitle: q(r.subtitle),
    tradition: q(r.tradition),
    dimension_category: q(r.dimension_category),
    intro: q(r.intro),
    cover_emoji: q(r.cover_emoji),
    estimated_minutes: String(r.estimated_minutes),
    question_count: String(r.question_count),
    questions: jsonb(r.questions),
    scoring_logic: jsonb(r.scoring_logic),
    result_types: jsonb(r.result_types),
    engine_hooks: jsonb(r.engine_hooks),
    version: String(r.version),
    is_active: 'true',
    is_featured: 'false',
    sort_order: String(r.sort_order),
    updated_at: 'now()',
  };
  return `    (${COLUMNS.map((c) => map[c]).join(', ')})`;
}

const UPDATABLE = COLUMNS.filter(
  (c) => !['slug', 'is_active', 'is_featured', 'sort_order', 'updated_at'].includes(c),
);

function emitSql(banks) {
  const sorted = [...banks].sort((a, b) => a.slug.localeCompare(b.slug));

  const lines = [];
  lines.push('-- ═══════════════════════════════════════════════════════════════════════════');
  lines.push('-- MIRROR BANKS — generated by scripts/emit-mirror-migrations.mjs');
  lines.push('--');
  lines.push('-- Source of truth: src/data/mirrors/registry.ts');
  lines.push('-- Do not hand-edit this file. Edit the registry and re-run the emitter.');
  lines.push(`--`);
  lines.push(`-- Banks in this migration: ${sorted.length}`);
  lines.push('--');
  lines.push('-- Each bank is stored at the SURFACE tier. The adaptive engine re-tiers it at');
  lines.push('-- read time from the user\'s confidence, so a stored bank never loses depth.');
  lines.push('-- ═══════════════════════════════════════════════════════════════════════════');
  lines.push('');
  lines.push('BEGIN;');
  lines.push('');

  for (const bank of sorted) {
    lines.push(`-- ${bank.title} (${bank.module})`);
    lines.push('INSERT INTO public.assessment_definitions (');
    lines.push(`  ${COLUMNS.join(',\n  ')}`);
    lines.push(') VALUES');
    lines.push(rowFor(bank));
    lines.push('ON CONFLICT (slug) DO UPDATE SET');
    lines.push(UPDATABLE.map((c) => `  ${c} = EXCLUDED.${c}`).join(',\n'));
    lines.push(';');
    lines.push('');
  }

  lines.push('COMMIT;');
  lines.push('');
  return lines.join('\n');
}

// ─── Main ───

const mod = await loadRegistry();
const {
  MIRROR_BANKS,
  MIRROR_BY_SLUG,
  MIRROR_ROWS,
  registryIssues,
  UNRESOLVED_SLUGS,
  NORMALISED,
  LEGACY_SLUGS_NOT_AUTHORED,
} = mod;

const missing = [...UNRESOLVED_SLUGS];
const authored = new Set(MIRROR_BANKS.map((b) => b.slug));
const referenced = await loadCheckpoints();
const orphaned = [...authored].filter((s) => !referenced.includes(s));

console.log(`Registry: ${MIRROR_BANKS.length} banks authored`);
console.log(`Referenced by mirrors.ts: ${referenced.length} unique slugs`);
if (NORMALISED?.length) {
  const byMode = {};
  for (const n of NORMALISED) byMode[n.mode] = (byMode[n.mode] ?? 0) + 1;
  const detail = Object.entries(byMode)
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `${k}=${v}`)
    .join(' ');
  console.log(`Repaired:  ${NORMALISED.length} question(s) with non-dimension weights (${detail})`);
}
if (LEGACY_SLUGS_NOT_AUTHORED?.length) {
  console.log(
    `Legacy:    ${32 - LEGACY_SLUGS_NOT_AUTHORED.length}/32 of the former DB-resident banks authored`,
  );
}

if (registryIssues?.length) {
  console.log('\nRegistry issues:');
  for (const issue of registryIssues) console.log(`  - ${issue}`);
}
if (missing.length) {
  console.log(`\nMISSING (referenced, not authored): ${missing.length}`);
  for (const s of missing) console.log(`  - ${s}`);
}
if (orphaned.length) {
  console.log(`\nOrphaned (authored, not referenced): ${orphaned.length}`);
  for (const s of orphaned) console.log(`  - ${s}`);
}

if (checkOnly) {
  process.exit(missing.length || registryIssues?.length ? 1 : 0);
}

if (missing.length) {
  console.error('\nRefusing to emit — unresolved slugs above.');
  process.exit(1);
}

const sql = emitSql(MIRROR_ROWS);
const hash = createHash('sha256').update(sql).digest('hex').slice(0, 8);

// Reuse the existing mirror migration when the banks have not changed, so
// re-running does not litter the migrations folder.
let target = explicitOut;
if (!target && existsSync(migrationsDir)) {
  const existing = (await readdir(migrationsDir)).find((f) =>
    /^_?\d*_?mirror_banks/.test(f),
  );
  if (existing) target = path.join(migrationsDir, existing);
}
if (!target) target = path.join(migrationsDir, '20260930000000_mirror_banks.sql');

await mkdir(path.dirname(target), { recursive: true });
await writeFile(target, sql, 'utf8');

console.log(`\nWrote ${target}`);
console.log(`Content hash: ${hash}`);
console.log(`Mirror banks live in the registry: ${MIRROR_BY_SLUG.size} slugs`);

void outIndex;
