/**
 * The 9 Core Skills of Consciousness — progressive levels (L0..L6).
 * Each skill is independent of path. Anyone can develop any skill.
 */

export type SkillSlug =
  | "observation"
  | "self-inquiry"
  | "kriya"
  | "surrender"
  | "devotion"
  | "service"
  | "breath"
  | "stillness"
  | "witness";

export interface SkillLevel {
  level: number;
  name: string;
  markers: string[];
  microPractice: string;
  graduation: string;
}

export interface SkillEntry {
  slug: SkillSlug;
  name: string;
  essence: string;
  dimension: string;       // which dimension it primarily develops
  pairedPath: string;      // which yoga path uses this most
  levels: SkillLevel[];
}

const lvl = (
  level: number,
  name: string,
  markers: string[],
  microPractice: string,
  graduation: string,
): SkillLevel => ({ level, name, markers, microPractice, graduation });

