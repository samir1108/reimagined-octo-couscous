/**
 * ARC CATALOG — six cross-concept sequences.
 * Observer is the reference; the four path arcs are Level 1 of Bhakti, Jnana,
 * Karma, and Raja. Each arc is five sits, one door per sit.
 */

import { OBSERVER_ARC } from "@/lib/prescription/myths";
import type { ArcDefinition, ArcSit } from "./types";

function sit(
  index: number,
  title: string,
  concept: string,
  practice: string,
  minutes: number,
  teaching: string,
  practiceText: string,
  question: string,
  trap: string,
  carry: string,
): ArcSit {
  return {
    index,
    title,
    concept,
    practice,
    minutes,
    teaching,
    practiceText,
    question,
    trap,
    carry,
  };
}

