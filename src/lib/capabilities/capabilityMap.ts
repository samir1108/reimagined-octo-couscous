export function getCapabilityBySlug(slug: string): Capability | undefined {
  return CAPABILITIES.find((c) => c.slug === slug);
}

export function getCapabilityById(id: string): Capability | undefined {
  return CAPABILITIES.find((c) => c.id === id);
}

export function getCapabilitiesByDomain(domain: CapabilityDomain): Capability[] {
  return CAPABILITIES.filter((c) => c.domain === domain);
}

export function getLevelLabel(level: CapabilityLevel): string {
  const labels: Record<CapabilityLevel, string> = {
    0: "Unobserved",
    1: "Can Notice",
    2: "Can Sustain",
    3: "Can Regulate",
    4: "Can Apply",
    5: "Under Pressure",
  };
  return labels[level];
}

