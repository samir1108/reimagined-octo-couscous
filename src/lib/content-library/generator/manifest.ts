export const MAIN_CATEGORIES = CATEGORY_SPECS.filter((c) => !c.additional);
export const ADDITIONAL_CATEGORIES = CATEGORY_SPECS.filter((c) => c.additional);

export const MAIN_TOTAL = MAIN_CATEGORIES.reduce((s, c) => s + c.subcategories.reduce((a, b) => a + b.count, 0), 0);
export const ADDITIONAL_TOTAL = ADDITIONAL_CATEGORIES.reduce((s, c) => s + c.subcategories.reduce((a, b) => a + b.count, 0), 0);
export const GRAND_TOTAL = MAIN_TOTAL + ADDITIONAL_TOTAL;

export function getCategorySpec(slug: string): CategorySpec | undefined {
  return CATEGORY_SPECS.find((c) => c.slug === slug);
}

export function getCategoryCount(slug: string): number {
  const spec = getCategorySpec(slug);
  if (!spec) return 0;
  return spec.subcategories.reduce((s, sub) => s + sub.count, 0);
}

export function getAllSubcategorySlugs(): string[] {
  return CATEGORY_SPECS.flatMap((c) => c.subcategories.map((s) => s.slug));
}
