/**
 * GUIDE MODE FRAMEWORKS
 * ─────────────────────────────────────────────────────────────
 * For every Guide mode (25+), this file defines the FULL operating
 * framework the AI (and the UI) uses:
 *
 *   • purpose      — one line: what this mode IS for
 *   • whenToUse    — signals a user is in the right mode
 *   • notFor       — where this mode is the WRONG tool
 *   • lineage      — where the technique comes from (yoga, therapy…)
 *   • duration     — expected session length
 *   • arc          — 3–6 phases the conversation should walk through
 *   • techniques   — concrete moves the guide uses in this mode
 *   • dos / donts  — hard rails
 *   • openers      — sample first prompts (rotate, not scripted)
 *   • exitCriteria — how we know this session should close
 *   • successSignal — what "landed" looks like in the user
 *
 * The AI system prompt appends `mode.aiFramework` (compact form).
 * The UI shows the human-readable framework in a bottom sheet
 * so the user knows what they just picked.
 * ───────────────────────────────────────────────────────────── */

export interface GuideModeFramework {
  id: string;
  purpose: string;
  whenToUse: string[];
  notFor: string[];
  lineage: string;
  duration: string;      // "5–10 min", "10–20 min"...
  arc: { phase: string; goal: string }[];
  techniques: string[];
  dos: string[];
  donts: string[];
  openers: string[];
  exitCriteria: string[];
  successSignal: string;
}

/** Compact string the prompt director injects into the system prompt. */
export function toAIFramework(f: GuideModeFramework): string {
  return [
    `FRAMEWORK · ${f.id.toUpperCase()}`,
    `Purpose: ${f.purpose}`,
    `Lineage: ${f.lineage}`,
    `Arc (walk in order, one phase at a time — do not skip):`,
    ...f.arc.map((a, i) => `  ${i + 1}. ${a.phase} — ${a.goal}`),
    `Core techniques: ${f.techniques.join(" · ")}`,
    `DO: ${f.dos.join(" | ")}`,
    `DON'T: ${f.donts.join(" | ")}`,
    `Exit when: ${f.exitCriteria.join(" | ")}`,
    `Landed = ${f.successSignal}`,
  ].join("\n");
}

