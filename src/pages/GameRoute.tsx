/** Every game id that actually has a component. Data modules assert against this. */
export const GAME_LOADER_IDS = Object.keys(loaders);

export function hasGameLoader(gameId: string): boolean {
  return Object.prototype.hasOwnProperty.call(loaders, gameId);
}

export default function GameRoute() {
  const { gameId = "" } = useParams();
  const game = getGame(gameId) || getLabGame(gameId);
  if (!game || !loaders[gameId]) {
    return <Navigate to="/app/games" replace />;
  }
  const Comp = lazy(loaders[gameId]);
  return (
    <Suspense fallback={<div className="fixed inset-0 bg-black" />}>
      <Comp />
    </Suspense>
  );
}
